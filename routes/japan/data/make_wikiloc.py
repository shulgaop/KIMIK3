ДВИЖОК = КОРЕНЬ.parent.parent / "route_app" / "scripts"
ВЫХОД = КОРЕНЬ / "generated" / "викилок"


def _gpx_analyze():
    """Импортирует движок анализа GPX без запуска модуля."""
    spec = importlib.util.spec_from_file_location(
        "gpx_analyze", ДВИЖОК / "gpx_analyze.py")
    модуль = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(модуль)
    return модуль


def _статистика(gpx: Path) -> dict:
    """Км, набор/сброс и диапазон высот трека — только кодом."""
    ga = _gpx_analyze()
    точки, _ = ga.load_gpx(str(gpx))
    дист = ga.cumulative(точки)
    # Набор/сброс — через общий leg_stats движка на полном треке,
    # чтобы не дублировать логику накопления дельт высот.
    стат = ga.leg_stats(точки, дист, 0, len(точки) - 1)
    высоты = [т[2] for т in точки]
    return {
        "км": дист[-1] / 1000,
        "набор": стат["gain_m"],
        "сброс": стат["loss_m"],
        "мин": round(min(высоты)),
        "макс": round(max(высоты)),
    }


