ФОТО_ЧЕКЛИСТ = """
## Чек-лист перед публикацией

- [ ] Трек на карте совпадает с пройденным, «полёты» GPS обрезаны
- [ ] Название содержит регион (Кумано Кодо / Фудзи) — так находят в поиске
- [ ] Сложность и опасности не занижены
- [ ] Все `[ПО ФАКТУ]` заменены реальными наблюдениями
- [ ] Фото без лиц посторонних и личных данных
"""


def _дополнить_высоты(точки: list, gpx: Path) -> None:
    """Заполняет ele=None высотой трека в точке ближайшего километража.

    Боковые точки (вершина Фудзи, Юноминэ, Оюнохара) лежат вне линии трека,
    высоту им не присваивали — берём кодом из GPX, не «на глаз».
    """
    ga = _gpx_analyze()
    трек, _ = ga.load_gpx(str(gpx))
    дист = ga.cumulative(трек)
    for т in точки:
        if т.get("ele") is None:
            цель = т["track_km"] * 1000
            ближайший = min(range(len(трек)), key=lambda i: abs(дист[i] - цель))
            т["ele"] = трек[ближайший][2]


def _черновик(трек: dict) -> str:
    """Один markdown-черновик отчёта Wikiloc по треку."""
    стат = _статистика(трек["gpx"])
    точки = json.loads(трек["points"].read_text(encoding="utf-8"))
    _дополнить_высоты(точки, трек["gpx"])

    строки_точек = []
    for номер, т in enumerate(точки, 1):
        подпись = т.get("note", "")
        строки_точек.append(
            f"| {номер} | {т['name']} ({т['jp']}) | {т['lat']:.5f} | "
            f"{т['lon']:.5f} | {round(т['ele'])} | {т['track_km']:.1f} | "
            f"{подпись} |")
    таблица_точек = (
        "| № | Название (jp) | Широта | Долгота | Высота, м | км трека | "
        "Подпись/фото |\n|---|---|---|---|---|---|---|\n"
        + "\n".join(строки_точек))

    фото = "\n".join(f"- [ ] {п}" for п in трек["фото"])

    описание = f"""{трек['обзор']}

ДИСТАНЦИЯ И ВРЕМЯ: {стат['км']:.1f} км, набор +{стат['набор']} м / сброс \
−{стат['сброс']} м, высоты {стат['мин']}–{стат['макс']} м. Чистое ходовое \
время [ПО ФАКТУ]; с остановками [ПО ФАКТУ].

КАК ДОБРАТЬСЯ: {трек['добраться']}

НАВИГАЦИЯ: {трек['навигация']}

ВОДА И ЕДА: {трек['вода']}

ПОКРЫТИЕ И ОБУВЬ: {трек['покрытие']}

СЕЗОН: {трек['сезон']}

ОПАСНОСТИ: {трек['опасности']}

ИНТЕРЕСНОЕ НА МАРШРУТЕ: {трек['интересное']}

ПРОЙДЕНО: [дата — ПО ФАКТУ], компания [N], погода [ПО ФАКТУ]."""

    return f"""# Wikiloc-черновик: {трек['название']}

Заполнено кодом (`make_wikiloc.py`) из данных маршрута «Япония 2027»;
цифры — расчёт по GPX. Форма-шаблон — `templates/Викилок_форма_отчёта.md`.
Блоки `[ПО ФАКТУ]` заполняются только реальными наблюдениями после
прохождения.

## Поля формы Wikiloc

| Поле | Значение |
|---|---|
| Название | {трек['название']} |
| Активность | {трек['активность']} |
| Сложность | {трек['сложность']} |
| Тип | {трек['тип']} |
| Дистанция / набор | из GPX: {стат['км']:.1f} км, +{стат['набор']} м / −{стат['сброс']} м (проверить расчёт Wikiloc) |
| Видимость | Публичный |
| GPX | `{трек['gpx'].name}` (лежит рядом в `data/` или в срезе дня) |

## Текст описания (вставить в Wikiloc, plain text)

```
{описание}
```

## Точки (waypoints)

{таблица_точек}

## Фото-план

{фото}
{ФОТО_ЧЕКЛИСТ}"""


def main() -> None:
    """Генерирует черновики всех треков в generated/викилок/."""
    ВЫХОД.mkdir(parents=True, exist_ok=True)
    for трек in ТРЕКИ:
        путь = ВЫХОД / трек["файл"]
        путь.write_text(_черновик(трек) + "\n", encoding="utf-8")
        print(f"✓ {путь.name}")


if __name__ == "__main__":
    main()
