"""make_wikiloc.py — черновики отчётов Wikiloc для треков маршрута «Япония».

Собирает по одному заполненному черновику на трек в
`generated/викилок/`: поля формы Wikiloc, готовый текст описания
(plain text, с пометками [ПО ФАКТУ] — заполняются после прохождения),
таблица точек с координатами из `points.json`, фото-план и чек-лист.
Километраж и наборы считает кодом по GPX через движок
(`route_app/scripts/gpx_analyze.py`), не «на глаз».

Форма-шаблон — `templates/Викилок_форма_отчёта.md`.

Запуск (из каталога routes/japan/data/):
    python make_wikiloc.py
"""

