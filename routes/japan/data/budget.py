#!/usr/bin/env python3
"""budget.py — расчёт бюджета маршрута Японии кодом (D-009, T-006).

Все суммы — из официальных источников 2026 (помечены `проверить` к 2027),
НИКАКИХ чисел «из головы»: где цены нет — стоит None и строка не считается.
Конвертация JPY→EUR — живой курс open.er-api.com через движок currency.py.
Лимиты: €1500 основной + €1000 резерв (D-009). Авиабилеты не входят
(не куплены, S-007).

Использование: python3 budget.py
Выход: ../generated/Бюджет.md + stdout-сводка.
"""
import importlib.util
import sys
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "route_app" / "scripts"))
_spec = importlib.util.spec_from_file_location(
    "currency", Path(__file__).resolve().parents[3] / "route_app" / "scripts" / "currency.py")
cur = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(cur)

OUT = Path(__file__).resolve().parent.parent / "generated" / "Бюджет.md"
MAIN_EUR, RESERVE_EUR = 1500, 1000  # D-009

# (статья, ¥, источник/пометка). Все цены — ориентиры 2026, `проверить` к 2027.
ITEMS = [
    ("Транспорт", [
        ("N'EX Нарита → Синдзюку", 3300, "JR East 2026, `проверить`"),
        ("Автобус Синдзюку ↔ 5-я станция Фудзи (2 рейса)", 9600, "S-028: ¥4800/рейс, `проверить`"),
        ("Синкансэн Нодзоми Токио → Киото (резерв.)", 14400, "JR 2026, `проверить`"),
        ("Куросио Киото/Син-Осака → Кии-Танабэ", 6500, "JR 2026, `проверить`"),
        ("Куросио Сингу → Син-Осака", 8000, "JR 2026, `проверить`"),
        ("Автобусы Кумано (Танабэ→Такидзири, Хонгу→Юноминэ, Когути→Нати, Нати→Кацуура)", 3500, "Kumano Kotsu 2026, `проверить`"),
        ("Городской транспорт (Suica, пополнение)", 3000, "оценка по тарифам 2026"),
        ("Трансфер в Кансай (Нанкай/Харука)", 1500, "2026, `проверить`"),
    ]),
    ("Жильё (8 ночей)", [
        ("Токио, Синдзюку (1 ночь)", 12000, "бизнес-отель 2026, `проверить`"),
        ("Хижина 8-й станции Фудзи, полупансион (1 ночь)", 10000, "S-031: ¥8000–12000, `проверить`"),
        ("Киото у вокзала (1 ночь)", 12000, "2026, `проверить`"),
        ("Кии-Танабэ (1 ночь)", 9000, "2026, `проверить`"),
        ("Минсюку Цугизакура/Нонака, полупансион (1 ночь)", 10500, "kumano-travel 2026, `проверить`"),
        ("Юноминэ-онсэн, полупансион (1 ночь)", 12000, "kumano-travel 2026, `проверить`"),
        ("Кацуура, рёкан с банями (1 ночь)", 15000, "2026, `проверить`"),
        ("Осака (1 ночь)", 11000, "2026, `проверить`"),
    ]),
    ("Питание", [
        ("Города (Токио, Киото, Осака, Танабэ): ~¥4500/день × 5", 22500, "средний чек 2026"),
        ("Трековые дни: перекусы/обеды ~¥1500/день × 4", 6000, "Чикатацию, Когути, хижины"),
    ]),
    ("Прочее", [
        ("Взнос на тропу Фудзи", 4000, "S-011: сезон 2026, `перепроверить` к 2027"),
        ("Онсэны: Цубою (слот 30 мин), Каваю/Кацуура", 2500, "S-020, S-021, `проверить`"),
        ("Смотровая водопада Нати и мелкие входы", 1000, "S-022, `проверить`"),
        ("Сувениры/амулеты (ятагарасу и пр.)", 3000, "по желанию"),
    ]),
]


def main():
    rates = cur.fetch_rates("EUR")
    jpy_per_eur = rates["rates"]["JPY"]
    rate_date = rates.get("time_last_update_utc", "?")
    lines = [f"# Бюджет маршрута Японии (02–10.09.2027)",
             "",
             f"Курс: 1 € = {jpy_per_eur:.2f} ¥ (open.er-api.com, обновлено {rate_date}).",
             "Авиабилеты не входят (не куплены, S-007). Все цены — ориентиры 2026,",
             "помечены `проверить` к сезону 2027. Расчёт — кодом (`budget.py`, D-009).",
             ""]
    total = 0
    for section, rows in ITEMS:
        sub = sum(j for _, j, _ in rows if j)
        total += sub
        lines += [f"## {section} — ¥{sub:,} (≈ €{sub / jpy_per_eur:.0f})", "",
                  "| Статья | ¥ | Пометка |", "|---|---|---|"]
        for name, jpy, note in rows:
            v = f"{jpy:,}" if jpy else "—"
            lines.append(f"| {name} | {v} | {note} |")
        lines.append("")
    eur = total / jpy_per_eur
    lines += ["---",
              f"## Итого: ¥{total:,} ≈ **€{eur:.0f}**",
              "",
              f"- Лимит основной: €{MAIN_EUR} → {'укладываемся' if eur <= MAIN_EUR else 'ПРЕВЫШЕНИЕ'} "
              f"(запас {eur / MAIN_EUR * 100 - 100:+.0f}% к лимиту)",
              f"- Резерв («хотелки» и экстренные): €{RESERVE_EUR} — не расходуется в плановом сценарии.",
              f"- Расчёт на 1 человека; при двоих жильё и часть расходов делятся.",
              "",
              f"_Сгенерировано кодом {date.today().isoformat()}; перепроверка цен — весна–лето 2027 (S-007, S-008, S-013)._"]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"✓ {OUT}")
    print(f"Итого ¥{total:,} ≈ €{eur:.0f} (лимит €{MAIN_EUR}+€{RESERVE_EUR})")


if __name__ == "__main__":
    main()
